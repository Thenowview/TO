"use strict";
const fs=require("node:fs"),path=require("node:path"),crypto=require("node:crypto"),assert=require("node:assert/strict");
const [src,dest,keyFile,idFile]=process.argv.slice(2);
if(!src||!dest||!keyFile||!idFile)throw Error("Need source, target, public key and extension ID");
const source=path.resolve(src),target=path.resolve(dest);
if(source===target)throw Error("Source and destination must differ");
const key=fs.readFileSync(keyFile,"utf8").trim(),expected=fs.readFileSync(idFile,"utf8").trim();
assert.match(key,/^[A-Za-z0-9+/]+={0,2}$/);
assert.match(expected,/^[a-p]{32}$/);
const der=Buffer.from(key,"base64");
if(der.length<100||der.length>4096||der.toString("base64")!==key)throw Error("Invalid public key");
const digest=crypto.createHash("sha256").update(der).digest().subarray(0,16);
const id=[...digest].map(b=>"abcdefghijklmnop"[b>>4]+"abcdefghijklmnop"[b&15]).join("");
assert.equal(id,expected,"Manifest key ID mismatch");
fs.cpSync(source,target,{recursive:true});
const p=path.join(target,"manifest.json"),manifest=JSON.parse(fs.readFileSync(p,"utf8"));
if(manifest.manifest_version!==3||!manifest.permissions.includes("nativeMessaging"))throw Error("Native Messaging permission missing");
manifest.key=key;
fs.writeFileSync(p,JSON.stringify(manifest,null,2)+"\n");
console.log("PASS fixed Chrome extension ID:",id);
