import { readFileSync } from 'node:fs';
import { Script } from 'node:vm';
import assert from 'node:assert/strict';
const html=readFileSync(new URL('./index.html',import.meta.url),'utf8');
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)];
assert.equal(scripts.length,1,'Exactly one trusted inline script');
new Script(scripts[0][1],{filename:'theorg-intelligence.js'});
for(const id of ['overview','agents','portfolio','risk','decisions','knowledge','metricSelect','orderList','decisionList','taskInput','draftBtn'])assert.match(html,new RegExp('id="'+id+'"'),'Missing '+id);
assert.match(html,/Synthetic data|synthetic scenario/i,'Must label synthetic demo');
assert.match(html,/No connection to THEEPMO systems/,'Enforce standalone boundary');
assert.match(html,/function calculate\(\)/,'Deterministic KPI workbench');
assert.match(html,/localStorage\.setItem/,'Local-only demo persistence');
assert.match(html,/function audit\(o,status\)/,'Auditable demo-state transitions');
assert.match(html,/o\.status==='qa-reviewed'/,'QA gate on simulated closure');
assert.match(html,/const escape=s=>/,'Escape untrusted task content');
assert.doesNotMatch(html,/<script\b[^>]*src=|<link\b[^>]*href=/i,'No third party scripts/styles');
assert.doesNotMatch(html,/\bfetch\s*\(|XMLHttpRequest|navigator\.sendBeacon/,'Demo must not make network requests');
assert.doesNotMatch(html,/https?:\/\/[^'"]+\.theepmo\.com/i,'No THEEPMO API integration');
console.log('TheOrg Intelligence source contract: PASS');
